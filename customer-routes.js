const express = require("express");
const crypto = require("crypto");
const { promisify } = require("util");

const scrypt = promisify(crypto.scrypt);
const SESSION_LIFETIME = 7 * 24 * 60 * 60 * 1000;

module.exports = function createCustomerRoutes(pool, storageConfig = {}) {
    const supabase = storageConfig.supabase || null;
    const STORAGE_BUCKET = storageConfig.storageBucket || "appointment-results";
    const router = express.Router();
    const loginAttempts = new Map();

    function hashToken(token) {
        return crypto.createHash("sha256").update(token).digest("hex");
    }

    function getCookie(req) {
        const cookies = req.headers.cookie || "";
        const match = cookies.match(/(?:^|;\s*)lma_customer=([a-f0-9]{64})/);
        return match ? match[1] : "";
    }

    function setSessionCookie(res, token) {
        const secure = process.env.NODE_ENV === "production" ? "; Secure" : "";
        res.setHeader(
            "Set-Cookie",
            "lma_customer=" + token +
            "; HttpOnly; SameSite=Lax; Path=/; Max-Age=604800" + secure
        );
    }

    async function createSession(customerId, res) {
        const token = crypto.randomBytes(32).toString("hex");
        const expiresAt = new Date(Date.now() + SESSION_LIFETIME);

        await pool.query(
            `INSERT INTO public.customer_sessions
             (token_hash, customer_id, expires_at)
             VALUES ($1, $2, $3)`,
            [hashToken(token), customerId, expiresAt]
        );

        setSessionCookie(res, token);
    }

    async function getCustomerFromRequest(req) {
        const token = getCookie(req);
        if (!token) return null;

        const result = await pool.query(
            `SELECT a.id, a.email, a.full_name, a.contact, a.address
             FROM public.customer_sessions s
             JOIN public.customer_accounts a ON a.id = s.customer_id
             WHERE s.token_hash = $1 AND s.expires_at > NOW()`,
            [hashToken(token)]
        );

        return result.rows[0] || null;
    }

    async function requireCustomer(req, res, next) {
        try {
            const customer = await getCustomerFromRequest(req);

            if (!customer) {
                return res.status(401).json({
                    success: false,
                    message: "Mag-login muna sa iyong customer account."
                });
            }

            req.customer = customer;
            next();
        } catch (err) {
            console.error("Customer authentication error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-verify ang customer account."
            });
        }
    }

    async function initializeCustomerTables() {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS public.customer_accounts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_salt TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                full_name TEXT NOT NULL,
                contact TEXT NOT NULL,
                address TEXT NOT NULL DEFAULT '',
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        `);

        await pool.query(`
            CREATE TABLE IF NOT EXISTS public.customer_sessions (
                token_hash TEXT PRIMARY KEY,
                customer_id BIGINT NOT NULL
                    REFERENCES public.customer_accounts(id) ON DELETE CASCADE,
                expires_at TIMESTAMPTZ NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        `);

        await pool.query(`
            ALTER TABLE public.appointments
            ADD COLUMN IF NOT EXISTS customer_id BIGINT
            REFERENCES public.customer_accounts(id) ON DELETE SET NULL
        `);

        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_appointments_customer_id
            ON public.appointments (customer_id)
        `);
    }

    router.post("/api/customer/register", async (req, res) => {
        try {
            const fullName = String(req.body.fullName || "").trim();
            const contact = String(req.body.contact || "").trim();
            const address = String(req.body.address || "").trim();
            const email = String(req.body.email || "").trim().toLowerCase();
            const password = String(req.body.password || "");

            if (!fullName || !contact || !email || !password) {
                return res.status(400).json({
                    success: false,
                    message: "Punan ang pangalan, contact number, email, at password."
                });
            }

            if (
                fullName.length > 150 ||
                contact.length > 40 ||
                address.length > 500 ||
                email.length > 254 ||
                !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)
            ) {
                return res.status(400).json({
                    success: false,
                    message: "Suriin ang haba at format ng iyong impormasyon."
                });
            }

            if (password.length < 10 || password.length > 200) {
                return res.status(400).json({
                    success: false,
                    message: "Gumamit ng password na may hindi bababa sa 10 character."
                });
            }

            const salt = crypto.randomBytes(16).toString("hex");
            const derived = await scrypt(password, salt, 64);
            const passwordHash = derived.toString("hex");

            const result = await pool.query(
                `INSERT INTO public.customer_accounts
                 (email, password_salt, password_hash, full_name, contact, address)
                 VALUES ($1, $2, $3, $4, $5, $6)
                 RETURNING id`,
                [email, salt, passwordHash, fullName, contact, address]
            );

            await createSession(result.rows[0].id, res);

            res.status(201).json({
                success: true,
                message: "Matagumpay na nagawa ang customer account."
            });
        } catch (err) {
            if (err.code === "23505") {
                return res.status(409).json({
                    success: false,
                    message: "May account na gamit ang email na ito. Mag-login na lamang."
                });
            }

            console.error("Customer registration error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi nagawa ang account. Subukan muli mamaya."
            });
        }
    });

    router.post("/api/customer/login", async (req, res) => {
        const ip = req.ip || "unknown";
        const now = Date.now();
        let attempt = loginAttempts.get(ip);

        if (!attempt || now - attempt.startedAt > 15 * 60 * 1000) {
            attempt = { startedAt: now, count: 0 };
        }

        if (attempt.count >= 10) {
            loginAttempts.set(ip, attempt);
            return res.status(429).json({
                success: false,
                message: "Maraming login attempt. Maghintay ng 15 minuto bago sumubok muli."
            });
        }

        attempt.count += 1;
        loginAttempts.set(ip, attempt);

        try {
            const email = String(req.body.email || "").trim().toLowerCase();
            const password = String(req.body.password || "");

            const result = await pool.query(
                `SELECT id, password_salt, password_hash
                 FROM public.customer_accounts WHERE email = $1`,
                [email]
            );

            const account = result.rows[0];

            if (!account) {
                return res.status(401).json({
                    success: false,
                    message: "Hindi tama ang email o password."
                });
            }

            const derived = await scrypt(password, account.password_salt, 64);
            const actual = Buffer.from(derived);
            const expected = Buffer.from(account.password_hash, "hex");

            if (
                actual.length !== expected.length ||
                !crypto.timingSafeEqual(actual, expected)
            ) {
                return res.status(401).json({
                    success: false,
                    message: "Hindi tama ang email o password."
                });
            }

            loginAttempts.delete(ip);
            await createSession(account.id, res);

            res.json({
                success: true,
                message: "Matagumpay ang pag-login."
            });
        } catch (err) {
            console.error("Customer login error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi makapag-login sa ngayon."
            });
        }
    });

    router.get("/api/customer/me", requireCustomer, (req, res) => {
        res.json({
            success: true,
            customer: {
                id: req.customer.id,
                email: req.customer.email,
                fullName: req.customer.full_name,
                contact: req.customer.contact,
                address: req.customer.address
            }
        });
    });

    router.put("/api/customer/profile", requireCustomer, async (req, res) => {
        try {
            const fullName = String(req.body.fullName || "").trim();
            const contact = String(req.body.contact || "").trim();
            const address = String(req.body.address || "").trim();

            if (
                !fullName || !contact ||
                fullName.length > 150 ||
                contact.length > 40 ||
                address.length > 500
            ) {
                return res.status(400).json({
                    success: false,
                    message: "Suriin ang pangalan, contact number, at address."
                });
            }

            await pool.query(
                `UPDATE public.customer_accounts
                 SET full_name = $1, contact = $2, address = $3,
                     updated_at = NOW()
                 WHERE id = $4`,
                [fullName, contact, address, req.customer.id]
            );

            res.json({
                success: true,
                message: "Na-save ang iyong biodata."
            });
        } catch (err) {
            console.error("Customer profile error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi na-save ang profile."
            });
        }
    });

    router.get("/api/customer/appointments", requireCustomer, async (req, res) => {
        try {
            const result = await pool.query(
                `SELECT id, service, "preferredDate", "preferredTime",
                    "createdAt", status, "paymentTiming", "paymentMethod",
                    result_original_name AS "resultOriginalName",
                    (result_storage_path IS NOT NULL) AS "resultAvailable"
             FROM public.appointments
             WHERE customer_id = $1
             ORDER BY id DESC`,
                [req.customer.id]
            );

            res.json({ success: true, appointments: result.rows });
        } catch (err) {
            console.error("Customer appointments error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-load ang appointments."
            });
        }
    });


    router.get("/api/customer/appointments/:id/result", requireCustomer, async (req, res) => {
        try {
            if (!supabase) {
                return res.status(503).json({
                    success: false,
                    message: "Hindi pa naka-configure ang private storage."
                });
            }

            if (!/^\d+$/.test(req.params.id)) {
                return res.status(400).json({
                    success: false,
                    message: "Invalid appointment ID."
                });
            }

            const result = await pool.query(
                `SELECT result_storage_path, result_original_name
                 FROM public.appointments
                 WHERE id = $1 AND customer_id = $2`,
                [req.params.id, req.customer.id]
            );

            if (!result.rowCount || !result.rows[0].result_storage_path) {
                return res.status(404).json({
                    success: false,
                    message: "Walang result file na available para sa appointment na ito."
                });
            }

            const row = result.rows[0];
            const signed = await supabase.storage
                .from(STORAGE_BUCKET)
                .createSignedUrl(row.result_storage_path, 300);

            if (signed.error) throw signed.error;

            res.json({
                success: true,
                url: signed.data.signedUrl,
                fileName: row.result_original_name
            });
        } catch (err) {
            console.error("Customer result access error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-access ang resulta sa ngayon."
            });
        }
    });

    router.post("/api/customer/logout", async (req, res) => {
        try {
            const token = getCookie(req);

            if (token) {
                await pool.query(
                    "DELETE FROM public.customer_sessions WHERE token_hash = $1",
                    [hashToken(token)]
                );
            }

            const secure = process.env.NODE_ENV === "production" ? "; Secure" : "";
            res.setHeader(
                "Set-Cookie",
                "lma_customer=; HttpOnly; SameSite=Lax; Path=/; Max-Age=0" + secure
            );

            res.json({ success: true, message: "Naka-logout ka na." });
        } catch (err) {
            console.error("Customer logout error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi nakumpleto ang logout."
            });
        }
    });

    return {
        router,
        initializeCustomerTables,
        getCustomerFromRequest
    };
};
