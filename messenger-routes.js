const express = require("express");
const crypto = require("crypto");
const path = require("path");

module.exports = function createMessengerRoutes(pool, config) {
    const router = express.Router();
    const supabase = config.supabase;
    const bucket = config.storageBucket;
    const requireAdmin = config.requireAdmin;
    const fileUpload = config.fileUpload;

    function validId(value) {
        return typeof value === "string" && /^\d+$/.test(value);
    }

    async function customerExists(id) {
        const result = await pool.query(
            "SELECT id FROM public.customer_accounts WHERE id = $1",
            [id]
        );
        return result.rowCount > 0;
    }

    async function initializeMessengerTables() {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS public.customer_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id BIGINT NOT NULL
                    REFERENCES public.customer_accounts(id) ON DELETE CASCADE,
                sender_role TEXT NOT NULL
                    CHECK (sender_role IN ('admin', 'customer')),
                message TEXT,
                file_storage_path TEXT,
                file_original_name TEXT,
                file_content_type TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                CHECK (
                    NULLIF(TRIM(COALESCE(message, '')), '') IS NOT NULL
                    OR file_storage_path IS NOT NULL
                )
            )
        `);

        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_customer_messages_customer_created
            ON public.customer_messages (customer_id, created_at, id)
        `);
    }

    // Routes below are protected by the customer middleware supplied
    // by customer-routes.js through the authenticated request check.
    async function requireCustomer(req, res, next) {
        try {
            const cookies = req.headers.cookie || "";
            const match = cookies.match(/(?:^|;\s*)lma_customer=([a-f0-9]{64})/);
            if (!match) {
                return res.status(401).json({
                    success: false,
                    message: "Mag-login muna sa iyong customer account."
                });
            }

            const tokenHash = crypto.createHash("sha256")
                .update(match[1]).digest("hex");

            const result = await pool.query(`
                SELECT a.id, a.email, a.full_name, a.contact, a.address
                FROM public.customer_sessions s
                JOIN public.customer_accounts a ON a.id = s.customer_id
                WHERE s.token_hash = $1 AND s.expires_at > NOW()
            `, [tokenHash]);

            if (!result.rowCount) {
                return res.status(401).json({
                    success: false,
                    message: "Mag-login muna sa iyong customer account."
                });
            }

            req.customer = result.rows[0];
            next();
        } catch (err) {
            console.error("Messenger customer authentication error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-verify ang customer account."
            });
        }
    }

    router.get("/api/customer/messages", requireCustomer, async (req, res) => {
        try {
            const result = await pool.query(`
                SELECT id, sender_role AS "senderRole", message,
                       file_original_name AS "fileName",
                       (file_storage_path IS NOT NULL) AS "hasFile",
                       created_at AS "createdAt"
                FROM public.customer_messages
                WHERE customer_id = $1
                ORDER BY created_at ASC, id ASC
                LIMIT 500
            `, [req.customer.id]);

            res.json({ success: true, messages: result.rows });
        } catch (err) {
            console.error("Customer messages error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-load ang mga mensahe."
            });
        }
    });

    router.post("/api/customer/messages", requireCustomer, async (req, res) => {
        try {
            const message = String(req.body.message || "").trim();
            if (!message || message.length > 2000) {
                return res.status(400).json({
                    success: false,
                    message: "Maglagay ng mensaheng 1 hanggang 2000 character."
                });
            }

            const result = await pool.query(`
                INSERT INTO public.customer_messages
                    (customer_id, sender_role, message)
                VALUES ($1, 'customer', $2)
                RETURNING id, sender_role AS "senderRole", message,
                          created_at AS "createdAt"
            `, [req.customer.id, message]);

            res.status(201).json({
                success: true,
                message: result.rows[0]
            });
        } catch (err) {
            console.error("Customer send message error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi naipadala ang mensahe."
            });
        }
    });

    // CUSTOMER: files sent by admin, own account only
    router.get("/api/customer/files", requireCustomer, async (req, res) => {
        try {
            const result = await pool.query(`
                SELECT id, message,
                       file_original_name AS "fileName",
                       file_content_type AS "contentType",
                       created_at AS "createdAt"
                FROM public.customer_messages
                WHERE customer_id = $1
                  AND sender_role = 'admin'
                  AND file_storage_path IS NOT NULL
                ORDER BY created_at DESC, id DESC
            `, [req.customer.id]);

            res.json({ success: true, files: result.rows });
        } catch (err) {
            console.error("Customer files error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-load ang iyong files."
            });
        }
    });

    router.get("/api/customer/files/:id/download", requireCustomer, async (req, res) => {
        try {
            if (!validId(req.params.id) || !supabase) {
                return res.status(400).json({
                    success: false,
                    message: "Hindi ma-access ang file."
                });
            }

            const result = await pool.query(`
                SELECT file_storage_path, file_original_name
                FROM public.customer_messages
                WHERE id = $1
                  AND customer_id = $2
                  AND sender_role = 'admin'
                  AND file_storage_path IS NOT NULL
            `, [req.params.id, req.customer.id]);

            if (!result.rowCount) {
                return res.status(404).json({
                    success: false,
                    message: "Hindi makita ang file sa iyong account."
                });
            }

            const row = result.rows[0];
            const signed = await supabase.storage
                .from(bucket)
                .createSignedUrl(row.file_storage_path, 300);

            if (signed.error) throw signed.error;

            res.json({
                success: true,
                url: signed.data.signedUrl,
                fileName: row.file_original_name
            });
        } catch (err) {
            console.error("Customer file download error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-download ang file sa ngayon."
            });
        }
    });

    // ADMIN: inbox list
    router.get("/api/admin/customers", requireAdmin, async (req, res) => {
        try {
            const result = await pool.query(`
                SELECT a.id, a.full_name AS "fullName", a.email,
                       a.contact,
                       last.message AS "lastMessage",
                       last.created_at AS "lastMessageAt"
                FROM public.customer_accounts a
                LEFT JOIN LATERAL (
                    SELECT message, created_at
                    FROM public.customer_messages m
                    WHERE m.customer_id = a.id
                    ORDER BY m.created_at DESC, m.id DESC
                    LIMIT 1
                ) last ON TRUE
                ORDER BY last.created_at DESC NULLS LAST, a.id DESC
            `);

            res.json({ success: true, customers: result.rows });
        } catch (err) {
            console.error("Admin customer inbox error:", err.message);
            res.status(500).json({
                success: false,
                message: "Hindi ma-load ang customer inbox."
            });
        }
    });

    router.get("/api/admin/customers/:id/messages", requireAdmin, async (req, res) => {
        try {
            if (!validId(req.params.id)) {
                return res.status(400).json({
                    success: false, message: "Invalid customer ID."
                });
            }

            const result = await pool.query(`
                SELECT id, sender_role AS "senderRole", message,
                       file_original_name AS "fileName",
                       (file_storage_path IS NOT NULL) AS "hasFile",
                       created_at AS "createdAt"
                FROM public.customer_messages
                WHERE customer_id = $1
                ORDER BY created_at ASC, id ASC
                LIMIT 500
            `, [req.params.id]);

            res.json({ success: true, messages: result.rows });
        } catch (err) {
            console.error("Admin conversation error:", err.message);
            res.status(500).json({
                success: false, message: "Hindi ma-load ang conversation."
            });
        }
    });

    router.post("/api/admin/customers/:id/messages", requireAdmin, async (req, res) => {
        try {
            if (!validId(req.params.id)) {
                return res.status(400).json({
                    success: false, message: "Invalid customer ID."
                });
            }

            const message = String(req.body.message || "").trim();
            if (!message || message.length > 2000) {
                return res.status(400).json({
                    success: false,
                    message: "Maglagay ng mensaheng 1 hanggang 2000 character."
                });
            }

            if (!(await customerExists(req.params.id))) {
                return res.status(404).json({
                    success: false, message: "Hindi makita ang customer."
                });
            }

            const result = await pool.query(`
                INSERT INTO public.customer_messages
                    (customer_id, sender_role, message)
                VALUES ($1, 'admin', $2)
                RETURNING id, sender_role AS "senderRole", message,
                          created_at AS "createdAt"
            `, [req.params.id, message]);

            res.status(201).json({
                success: true, message: result.rows[0]
            });
        } catch (err) {
            console.error("Admin send message error:", err.message);
            res.status(500).json({
                success: false, message: "Hindi naipadala ang mensahe."
            });
        }
    });

    // ADMIN: upload a private file for one customer
    router.post(
        "/api/admin/customers/:id/files",
        requireAdmin,
        (req, res, next) => {
            fileUpload.single("file")(req, res, (err) => {
                if (err) {
                    return res.status(400).json({
                        success: false,
                        message: err.message || "Hindi tinanggap ang file."
                    });
                }
                next();
            });
        },
        async (req, res) => {
            let storagePath;
            try {
                if (!validId(req.params.id)) {
                    return res.status(400).json({
                        success: false, message: "Invalid customer ID."
                    });
                }
                if (!supabase) {
                    return res.status(503).json({
                        success: false,
                        message: "Hindi naka-configure ang private storage sa server."
                    });
                }
                if (!req.file) {
                    return res.status(400).json({
                        success: false,
                        message: "Pumili ng PDF, JPG, o PNG file."
                    });
                }
                if (!(await customerExists(req.params.id))) {
                    return res.status(404).json({
                        success: false, message: "Hindi makita ang customer."
                    });
                }

                const b = req.file.buffer;
                const mime = req.file.mimetype;
                const pdf = b.subarray(0, 1024).toString("latin1").includes("%PDF-");
                const jpg = b.length >= 3 && b[0] === 255 && b[1] === 216 && b[2] === 255;
                const png = b.length >= 8 && b.subarray(0, 8).equals(
                    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])
                );
                if (!((mime === "application/pdf" && pdf) ||
                      (mime === "image/jpeg" && jpg) ||
                      (mime === "image/png" && png))) {
                    return res.status(400).json({
                        success: false,
                        message: "Hindi tugma ang file content sa PDF, JPG, o PNG format."
                    });
                }

                const extension = path.extname(req.file.originalname).toLowerCase();
                const safeName = path.basename(req.file.originalname, extension)
                    .replace(/[^a-zA-Z0-9_-]/g, "_").slice(0, 80) || "document";

                storagePath = `messages/${req.params.id}/${Date.now()}-${crypto.randomUUID()}-${safeName}${extension}`;

                const uploaded = await supabase.storage.from(bucket).upload(
                    storagePath, b, { contentType: mime, upsert: false }
                );
                if (uploaded.error) throw uploaded.error;

                try {
                    const originalName = path.basename(req.file.originalname).slice(0, 200);
                    await pool.query(`
                        INSERT INTO public.customer_messages
                            (customer_id, sender_role, message,
                             file_storage_path, file_original_name, file_content_type)
                        VALUES ($1, 'admin', $2, $3, $4, $5)
                    `, [
                        req.params.id,
                        "Nagpadala ang admin ng file.",
                        storagePath,
                        originalName,
                        mime
                    ]);
                } catch (dbErr) {
                    await supabase.storage.from(bucket).remove([storagePath]);
                    throw dbErr;
                }

                res.status(201).json({
                    success: true,
                    message: "Naipadala ang file sa customer account."
                });
            } catch (err) {
                console.error("Admin customer file upload error:", err.message);
                res.status(500).json({
                    success: false,
                    message: "Hindi naipadala ang file."
                });
            }
        }
    );

    return { router, initializeMessengerTables };
};
