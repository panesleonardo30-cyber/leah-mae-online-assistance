// UPDATE - Update appointment
app.put("/api/appointments/:id", requireAdmin, async (req, res) => {
    const allowed = {
        fullName: '"fullName"',
        service: '"service"',
        contact: '"contact"',
        email: '"email"',
        address: '"address"',
        preferredDate: '"preferredDate"',
        preferredTime: '"preferredTime"',
        message: '"message"',
        status: '"status"'
    };

    const updates = [];
    const values = [];

    for (const [field, column] of Object.entries(allowed)) {
        if (Object.prototype.hasOwnProperty.call(req.body, field)) {
            values.push(req.body[field] ?? "");
            updates.push(`${column} = $${values.length}`);
        }
    }

    if (!updates.length) {
        return res.status(400).json({
            success: false,
            message: "No fields to update."
        });
    }

    values.push(req.params.id);

    try {
        const result = await pool.query(
            `UPDATE public.appointments SET ${updates.join(", ")} WHERE id = $${values.length}`,
            values
        );

        if (!result.rowCount) {
            return res.status(404).json({
                success: false,
                message: "Appointment not found."
            });
        }

        res.json({ success: true, message: "Appointment updated successfully." });
    } catch (err) {
        console.error("Appointment update error:", err.message);
        res.status(500).json({
            success: false,
            message: "Failed to update appointment."
        });
    }
});

