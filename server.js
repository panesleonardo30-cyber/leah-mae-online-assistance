function initializeDatabase(callback) {
    (async () => {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS public.appointments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "fullName" TEXT NOT NULL,
                service TEXT NOT NULL,
                contact TEXT NOT NULL,
                "createdAt" TEXT DEFAULT CURRENT_TIMESTAMP::text,
                email TEXT,
                "preferredDate" TEXT,
                "paymentTiming" TEXT,
                status TEXT DEFAULT 'Pending',
                "preferredTime" TEXT,
                address TEXT,
                message TEXT,
                "paymentMethod" TEXT,
                "requestKey" TEXT,
                "requestHash" TEXT
            )
        `);

        const columns = [
            ["email", "TEXT"],
            ["address", "TEXT"],
            ["preferredDate", "TEXT"],
            ["preferredTime", "TEXT"],
            ["message", "TEXT"],
            ["emergencyContactName", "TEXT"],
            ["emergencyContactRelationship", "TEXT"],
            ["emergencyContactNumber", "TEXT"],
            ["declarationAccuracy", "BOOLEAN DEFAULT FALSE"],
            ["privacyConsent", "BOOLEAN DEFAULT FALSE"],
            ["privacyConsentAt", "TIMESTAMPTZ"],
            ["paymentMethod", "TEXT"],
            ["paymentTiming", "TEXT"],
            ["status", "TEXT DEFAULT 'Pending'"],
            ["requestKey", "TEXT"],
            ["requestHash", "TEXT"],
            ["result_storage_path", "TEXT"],
            ["result_original_name", "TEXT"],
            ["result_content_type", "TEXT"],
            ["result_uploaded_at", "TIMESTAMPTZ"]
        ];

        for (const [name, definition] of columns) {
            await pool.query(
                `ALTER TABLE public.appointments ADD COLUMN IF NOT EXISTS "${name}" ${definition}`
            );
        }

        await pool.query(`
            CREATE UNIQUE INDEX IF NOT EXISTS idx_appointments_requestKey
            ON public.appointments ("requestKey")
        `);
    })().then(() => callback()).catch(callback);
}

